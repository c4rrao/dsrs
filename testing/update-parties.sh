#!/bin/bash
# Writes parties.py from the party ids bootstrap.canton printed. Run after every ledger wipe.

set -e

echo "=========================================="
echo "  Updating Party IDs from Canton"
echo "=========================================="
echo ""

if ! docker ps | grep -q dsrs-canton; then
    echo "❌ Error: Canton container is not running"
    echo "   Start it with: cd dev && docker-compose up -d"
    exit 1
fi

sleep 2

echo "Fetching party IDs from Canton logs..."

OPERATOR=$(docker logs dsrs-canton 2>&1 | grep "Operator Party:" | tail -1 | awk '{print $NF}')
AUDITOR=$(docker logs dsrs-canton 2>&1 | grep "Auditor Party:" | tail -1 | awk '{print $NF}')
ESCROW=$(docker logs dsrs-canton 2>&1 | grep "Escrow Party:" | tail -1 | awk '{print $NF}')
ALICE=$(docker logs dsrs-canton 2>&1 | grep "Alice Party:" | tail -1 | awk '{print $NF}')
BOB=$(docker logs dsrs-canton 2>&1 | grep "Bob Party:" | tail -1 | awk '{print $NF}')
CHARLIE=$(docker logs dsrs-canton 2>&1 | grep "Charlie Party:" | tail -1 | awk '{print $NF}')
DIANA=$(docker logs dsrs-canton 2>&1 | grep "Diana Party:" | tail -1 | awk '{print $NF}')
EVE=$(docker logs dsrs-canton 2>&1 | grep "Eve Party:" | tail -1 | awk '{print $NF}')

if [ -z "$OPERATOR" ] || [ -z "$AUDITOR" ] || [ -z "$ALICE" ] || [ -z "$BOB" ] || [ -z "$CHARLIE" ] || [ -z "$DIANA" ] || [ -z "$EVE" ]; then
    echo "❌ Error: Could not extract all party IDs from Canton logs"
    echo ""
    echo "Found:"
    echo "  Operator:    $OPERATOR"
    echo "  Auditor:     $AUDITOR"
    echo "  Escrow:      $ESCROW"
    echo "  Alice:       $ALICE"
    echo "  Bob:         $BOB"
    echo "  Charlie:     $CHARLIE"
    echo "  Diana:       $DIANA"
    echo "  Eve:         $EVE"
    echo ""
    echo "Canton may still be bootstrapping. Wait 30 seconds and try again."
    exit 1
fi

echo ""
echo "✓ Found party IDs:"
echo "  Operator:    $OPERATOR"
echo "  Auditor:     $AUDITOR"
echo "  Escrow:      $ESCROW"
echo "  Alice:       $ALICE"
echo "  Bob:         $BOB"
echo "  Charlie:     $CHARLIE"
echo "  Diana:       $DIANA"
echo "  Eve:         $EVE"
echo ""

cat > parties.py << EOF
# Generated by update-parties.sh.

TEST_PARTIES = {
    "alice": {
        "name": "$ALICE",
        "participant": 1,
        "role": "Buyer"
    },
    "bob": {
        "name": "$BOB",
        "participant": 1,
        "role": "Seller"
    },
    "charlie": {
        "name": "$CHARLIE",
        "participant": 1,
        "role": "Broker"
    },
    "diana": {
        "name": "$DIANA",
        "participant": 1,
        "role": "Consumer"
    },
    "eve": {
        "name": "$EVE",
        "participant": 1,
        "role": "Notary"
    },
}

OPERATOR_PARTY = "$OPERATOR"
AUDITOR_PARTY = "$AUDITOR"
ESCROW_PARTY = "$ESCROW"
EOF

echo "✓ Wrote parties.py with new party IDs"
echo ""
echo "=========================================="
echo "  Update Complete!"
echo "=========================================="
echo ""
echo "You can now run CLI commands:"
echo "  python3 cli.py contribute Alice Buyer TX-001 --city Lisbon --price 350000"
echo ""
